#!/usr/bin/env node
// The per-hull strategic speed table of docs/movement/SHIP-DEPENDENT-STRATEGIC-SPEED.md (Appendix A), generated
// from bm-ships/ships.json so the design doc can never disagree with what the game flies. Each row carries the
// rater's confidence and provenance next to the rating, so a playtest change ("the D'deridex feels too slow")
// can see whether it touches a lore anchor or a low-confidence BM-specific estimate.
//   node scripts/strategic-speed-table.mjs            print the table block
//   node scripts/strategic-speed-table.mjs --write    rewrite the block in the doc, between its markers
//   node scripts/strategic-speed-table.mjs --check    exit 1 if the doc's block differs from the catalogue
import fs from 'node:fs';

const shipsFile = new URL('../bm-ships/ships.json', import.meta.url);
const docFile = new URL('../docs/movement/SHIP-DEPENDENT-STRATEGIC-SPEED.md', import.meta.url);
export const BEGIN = '<!-- strategic-speed-table:begin (generated by scripts/strategic-speed-table.mjs; do not edit by hand) -->';
export const END = '<!-- strategic-speed-table:end -->';

// What a row's confidence and source mean for anyone changing it later.
export function provenance(s) {
  if (s.strategicSpeedBasis === 'rater:fallback (retired)') return 'BM estimate · rater fallback (retired class)';
  if (s.strategicSpeedBasis === 'rater:fallback') return 'BM estimate · rater role/class fallback';
  if (s.strategicSpeedConfidence === 'high') return 'lore anchor';
  if (s.strategicSpeedConfidence === 'medium') return 'lore-informed inference';
  return 'BM estimate · rater table';
}
const cell = (x) => String(x ?? '—').replace(/\|/g, '\\|').replace(/\n/g, ' ');

export function tableBlock(ships = JSON.parse(fs.readFileSync(shipsFile, 'utf8')).ships) {
  const rows = ships.slice().sort((a, b) => String(a.faction).localeCompare(String(b.faction)) || b.strategicSpeedRating - a.strategicSpeedRating || a.name.localeCompare(b.name));
  const count = (f) => ships.filter(f).length;
  const kinds = ['lore anchor', 'lore-informed inference', 'BM estimate · rater table', 'BM estimate · rater role/class fallback', 'BM estimate · rater fallback (retired class)'];
  const lines = [BEGIN, '',
    `${ships.length} classes. By provenance: ${kinds.map((k) => `${k} ${count((s) => provenance(s) === k)}`).join(' · ')}.`, '',
    '| id | class | faction | role | rating | multiplier | confidence | provenance | rater\'s basis |',
    '|---:|---|---|---|---:|---:|---|---|---|',
    ...rows.map((s) => `| ${s.id} | ${cell(s.name)} | ${cell(s.faction)} | ${cell(s.role)} | ${Number(s.strategicSpeedRating).toFixed(1)} | ${Number(s.strategicSpeed).toFixed(2)}× | ${cell(s.strategicSpeedConfidence)} | ${cell(provenance(s))} | ${cell(s.strategicSpeedNote)} |`),
    '', END];
  return lines.join('\n');
}

export function docBlock(text = fs.readFileSync(docFile, 'utf8')) {
  const a = text.indexOf(BEGIN), b = text.indexOf(END);
  return a < 0 || b < 0 ? null : text.slice(a, b + END.length);
}

const isMain = import.meta.url === `file://${process.argv[1]}`;
if (isMain) {
  const block = tableBlock();
  if (process.argv.includes('--write')) {
    const text = fs.readFileSync(docFile, 'utf8');
    const cur = docBlock(text);
    if (!cur) throw new Error('the doc has no table markers');
    fs.writeFileSync(docFile, text.replace(cur, block));
    console.log('strategic speed table written');
  } else if (process.argv.includes('--check')) {
    const ok = docBlock() === block;
    console.log(ok ? 'strategic speed table: the doc matches the catalogue' : 'strategic speed table: the doc differs from the catalogue (run with --write)');
    process.exit(ok ? 0 : 1);
  } else console.log(block);
}
